export function featureCounts() {
  let y = 0, p = 0, n = 0;
  for (const a of FEATURE_AREAS) for (const it of a.items) { const s = norm(it).s; if (s === 'y') y++; else if (s === 'p') p++; else n++; }
  return { y, p, n, total: y + p + n };
}
