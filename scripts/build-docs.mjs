// Bundles README + docs/*.md into src/lib/docs-content.ts so the Worker can serve /docs and the MCP search_docs tool.
// Run after editing docs: node scripts/build-docs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const pages = [
  ['readme', 'Overview', 'README.md'],
  ['deploy', 'Deploy to Cloudflare', 'docs/DEPLOY.md'],
  ['api', 'REST API', 'docs/API.md'],
  ['mcp', 'MCP server (AI tools)', 'docs/MCP.md'],
  ['deliverability', 'Deliverability', 'docs/DELIVERABILITY.md'],
  ['support', 'Support', 'docs/SUPPORT.md'],
  ['architecture', 'Architecture', 'docs/ARCHITECTURE.md'],
];
const docs = pages.map(([slug, title, file]) => ({ slug, title, body: readFileSync(file, 'utf8') }));
writeFileSync('src/lib/docs-content.ts', `// GENERATED by scripts/build-docs.mjs — do not edit by hand.\nexport interface DocPage { slug: string; title: string; body: string }\nexport const DOCS: DocPage[] = ${JSON.stringify(docs, null, 1)};\n`);
console.log('wrote', docs.length, 'pages');
